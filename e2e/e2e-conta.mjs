import { chromium } from 'playwright';
const base = process.env.BASE_URL ?? 'http://localhost:5173';
const b = await chromium.launch();
const errors = []; const log = [];
const c = await b.newContext({ viewport: { width: 1280, height: 900 } });
const p = await c.newPage();
p.on('pageerror', (e) => errors.push(e.message));
p.on('console', (m) => { if (m.type() === 'error' && !/401|404|400|503/.test(m.text())) errors.push(m.text()); });
const email = `excluir.${Date.now()}@teste.com`;
await p.goto(base + '/cadastro', { waitUntil: 'networkidle' });
await p.fill('#cadastro-nome', 'Conta Para Excluir');
await p.fill('#cadastro-email', email);
await p.fill('#cadastro-senha', 'senha-forte-123');
await p.check('#cadastro-consentimento');
await p.getByRole('button', { name: 'Criar conta' }).click();
await p.waitForURL(base + '/');
log.push('cadastro -> ' + new URL(p.url()).pathname);
await p.goto(base + '/conta', { waitUntil: 'networkidle' });
await p.fill('#conta-nome', 'Conta Atualizada');
await p.getByRole('button', { name: 'Salvar nome' }).click();
await p.waitForSelector('text=Nome atualizado.');
log.push('nome atualizado -> ok');
await p.fill('#end-cep', '37500-000');
await p.locator('#end-cep').blur();
await p.waitForTimeout(2500);
log.push('busca de CEP mensagem: ' + ((await p.locator('#end-cep-ajuda').innerText().catch(() => '(sem mensagem)'))));
log.push('logradouro após CEP: "' + (await p.inputValue('#end-logradouro')) + '"');
await p.fill('#end-logradouro', 'Rua Teste'); await p.fill('#end-numero', '10'); await p.fill('#end-cidade', 'Itajubá'); await p.fill('#end-uf', 'MG');
await p.getByRole('button', { name: 'Salvar endereço' }).click();
await p.waitForSelector('text=Endereço salvo.');
log.push('endereço salvo -> ok');
await p.screenshot({ path: process.argv[2], fullPage: true });
await p.fill('#conta-confirmacao', 'EXCLUIR');
await p.getByRole('button', { name: 'Excluir minha conta' }).click();
await p.waitForURL(base + '/', { timeout: 15000 });
await p.waitForSelector('nav a[href="/entrar"]');
log.push('exclusão -> voltou à home, sessão encerrada');
await b.close();
console.log(log.join('\n')); console.log('errors:', errors.length ? errors : 'none');
