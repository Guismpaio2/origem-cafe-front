import { chromium } from 'playwright';
const base = process.env.BASE_URL ?? 'http://localhost:5173';
const b = await chromium.launch();
const errors = []; const log = [];
const c = await b.newContext({ viewport: { width: 1280, height: 900 } });
const p = await c.newPage();
p.on('pageerror', (e) => errors.push(e.message));
p.on('console', (m) => { if (m.type() === 'error' && !/401|404|422|409/.test(m.text())) errors.push(m.text()); });
await p.goto(base + '/entrar', { waitUntil: 'networkidle' });
await p.fill('#login-email', 'cliente@origemcafe.test'); await p.fill('#login-senha', 'Cliente#2026');
await p.getByRole('button', { name: 'Entrar na minha conta' }).click(); await p.waitForURL(base + '/');
await p.goto(base + '/', { waitUntil: 'networkidle' });
const cafe = p.locator('a[href^="/produtos/"]').filter({ hasText: 'Sul de Minas' }).first();
await cafe.click();
await p.locator('label[for^="moagem-"]').first().click();
await p.locator('label[for^="peso-"]').first().click();
await p.waitForSelector('text=Assinar mensalmente', { timeout: 10000 });
await p.getByRole('button', { name: 'Assinar mensalmente' }).click();
await p.waitForSelector('text=Assinatura criada', { timeout: 10000 }).catch(() => {});
const msg = await p.locator('[role=status], [role=alert]').allInnerTexts();
log.push('ao assinar: ' + msg.join(' | '));
await p.goto(base + '/assinatura', { waitUntil: 'networkidle' });
await p.waitForSelector('h1:has-text("Clube mensal")');
const card = await p.locator('article').first().innerText().catch(() => '(sem assinatura)');
log.push('assinatura exibida: ' + card.replace(/\n/g, ' | '));
await p.screenshot({ path: process.argv[2], fullPage: true });
const pausar = p.getByRole('button', { name: 'Pausar' });
if (await pausar.count()) { await pausar.first().click(); await p.waitForSelector('text=Assinatura atualizada.'); log.push('pausada -> ok'); }
await p.getByRole('button', { name: 'Cancelar na próxima cobrança' }).first().click();
await p.waitForSelector('text=Cancelamento agendado', { timeout: 10000 });
log.push('cancelamento agendado -> ok');
await b.close();
console.log(log.join('\n')); console.log('errors:', errors.length ? errors : 'none');
