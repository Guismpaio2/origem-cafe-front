import { chromium } from 'playwright';
const base = process.env.BASE_URL ?? 'http://localhost:5173';
const browser = await chromium.launch();
const errors = [];
const c = await browser.newContext({ viewport: { width: 1280, height: 900 } });
const p = await c.newPage();
p.on('pageerror', (e) => errors.push(e.message));
p.on('console', (m) => { if (m.type() === 'error' && !/401|404/.test(m.text())) errors.push(m.text()); });
const count = () => p.locator('nav a[href="/carrinho"]').first().innerText();
await p.goto(base + '/', { waitUntil: 'networkidle' });
await p.click('a[href^="/produtos/"] >> nth=0');
await p.waitForSelector('text=Adicionar ao carrinho');
await p.locator('label[for^="moagem-"]').first().click();
await p.locator('label[for^="peso-"]').first().click();
await p.getByRole('button', { name: 'Adicionar ao carrinho' }).click();
await p.waitForSelector('text=Adicionado ao carrinho');
const guestCount = await count();
await p.reload({ waitUntil: 'networkidle' });
const afterReload = await count();
await p.goto(base + '/entrar', { waitUntil: 'networkidle' });
await p.fill('#login-email', 'cliente@origemcafe.test');
await p.fill('#login-senha', 'Cliente#2026');
await p.getByRole('button', { name: 'Entrar na minha conta' }).click();
await p.waitForURL(base + '/');
await p.waitForTimeout(800);
const afterLogin = await count();
await p.goto(base + '/carrinho', { waitUntil: 'networkidle' });
console.log('visitante:', guestCount.replace(/\s+/g,' '), '| após recarregar:', afterReload.replace(/\s+/g,' '), '| após login:', afterLogin.replace(/\s+/g,' '));
await p.goto(base + '/checkout', { waitUntil: 'networkidle' });
await p.waitForSelector('text=Confirmar pedido');
await p.fill('#end-cep', '37500-000'); await p.fill('#end-logradouro', 'Rua Teste'); await p.fill('#end-numero', '10'); await p.fill('#end-cidade', 'Itajubá'); await p.fill('#end-uf', 'MG');
await p.getByRole('button', { name: 'Confirmar pedido' }).click();
await p.waitForSelector('h1:has-text("Pedido")', { timeout: 15000 });
console.log('checkout após carrinho remoto ->', (await p.locator('h1').first().innerText()));
console.log('after order cart:', (await count()).replace(/\s+/g,' '));
await browser.close();
console.log('errors:', errors.length ? errors : 'none');
